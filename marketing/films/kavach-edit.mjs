/**
 * Builds films/kavach.edit.json — the Kavach film's edit map — from the plan
 * (films/kavach.plan.json) and the windows chosen by eye after watching each
 * generated clip (films/flow-kavach/windows.json).
 *
 *   node films/kavach-edit.mjs
 *   node films/cut.mjs kavach
 *
 * The plan says which picture covers which line and for how long; the clips
 * then decide which of their seconds are usable. A window override replaces
 * the plan's from/to for one beat+asset, a `still` holds one source second
 * with a slow push-in, and a `split` plays a window then holds its last clean
 * frame — for a shot whose person does something random partway through.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const FILMS = path.resolve(import.meta.dirname);
const plan = JSON.parse(readFileSync(path.join(FILMS, 'kavach.plan.json'), 'utf8'));
const winFile = path.join(FILMS, 'flow-kavach', 'windows.json');
const windows = existsSync(winFile) ? JSON.parse(readFileSync(winFile, 'utf8')) : {};

const ref = (asset) => (asset.startsWith('S') ? `kflow:${asset}` : `kgfx:${asset}`);
const round = (n) => Math.round(n * 1000) / 1000;

const map = {};
for (const [beat, b] of Object.entries(plan.beats)) {
  const parts = [];
  for (const s of b.segments) {
    const w = windows[`${beat}|${s.asset}`];
    if (w?.split) {
      // play the first window at 1x, hold the rest on the chosen frame
      const [a, hold] = w.split;
      /* stop playing on the frame that is then held: a hold picked a few
         frames before the end of the played part made the picture jump back
         into the freeze (S54: 7 frames, seen as a twitch in the final watch) */
      const end = hold.still >= a.from ? Math.min(a.to, hold.still + 1 / 24) : a.to;
      const first = Math.min(end - a.from, s.seconds - 1);
      const fr = w.frame ? { frame: w.frame } : {};
      parts.push({ ref: ref(s.asset), from: a.from, to: a.from + first, seconds: round(first), ...fr });
      parts.push({ ref: ref(s.asset), still: hold.still, push: 1.04, seconds: round(s.seconds - first), ...fr });
      continue;
    }
    const e = { ref: ref(s.asset), seconds: s.seconds };
    if (w?.still != null) Object.assign(e, { still: w.still, push: 1.05 });
    else if (w?.from != null) Object.assign(e, { from: w.from, to: w.to });
    else if (s.from != null) Object.assign(e, { from: s.from, to: s.to });
    if (w?.frame) e.frame = w.frame;     // a crop of its own, see cut.mjs renderSegment
    parts.push(e);
  }
  map[beat] = parts.length === 1 && Object.keys(parts[0]).length === 2 && !parts[0].ref.startsWith('kflow')
    ? parts[0].ref
    : parts;
}

writeFileSync(path.join(FILMS, 'kavach.edit.json'), JSON.stringify({
  note: 'Generated by films/kavach-edit.mjs from kavach.plan.json + flow-kavach/windows.json. Edit those, not this.',
  map,
}, null, 1) + '\n');

const stretched = Object.entries(map).flatMap(([beat, parts]) => [].concat(parts)
  .filter((p) => typeof p === 'object' && p.to != null)
  .map((p) => ({ beat, ref: p.ref, x: p.seconds / (p.to - p.from) }))
  .filter((p) => p.x > 1.32));
console.log(`  ${Object.keys(map).length} beats → films/kavach.edit.json`);
for (const s of stretched) console.log(`  ! ${s.beat} ${s.ref} stretched ${s.x.toFixed(2)}x`);
