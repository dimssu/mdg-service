/**
 * Builds films/kavach-short.edit.json — the short's edit map for films/cut.mjs —
 * from films/kavach-short.plan.json, whose segments already carry their own
 * windows (from/to, still, frame, push). Unlike the full film there is no
 * separate windows file: the short was cut on paper first (short/cut-sheet.json).
 *
 *   node films/short/edit.mjs && DRAFT=1 node films/cut.mjs kavach-short
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const FILMS = path.resolve(import.meta.dirname, '..');
const plan = JSON.parse(readFileSync(path.join(FILMS, 'kavach-short.plan.json'), 'utf8'));
const round = (n) => Math.round(n * 1000) / 1000;

/* Asset id → cut.mjs source. The two new Vertex shots live with the other
   Vertex renders in marketing/clips (no generator mark, so no crop). */
const CLIPS = { N1: 'clip:N1-inspection-door' };
const ref = (a) => CLIPS[a] ?? (a.startsWith('S') ? `kflow:${a}` : `kgfx:${a}`);
const cardLength = (a) => {
  const f = path.join(FILMS, 'graphics-kavach', 'clips', `${a}.mp4`);
  if (!existsSync(f)) return null;
  return Number(String(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f])).trim());
};

const map = {};
for (const [beat, b] of Object.entries(plan.beats)) {
  map[beat] = b.segments.map((s) => {
    const e = { ref: ref(s.asset), seconds: s.seconds };
    if (s.still != null) {
      /* "final frame held": the card's last fully-built frame; the renderer
         adds a 0.4 s tail that repeats it, so 0.1 s before the end is safe */
      const still = s.still === 'final' ? round((cardLength(s.asset) ?? 5) - 0.1) : s.still;
      Object.assign(e, { still, push: s.push ?? 1.05 });
    } else if (s.from != null) Object.assign(e, { from: s.from, to: s.to });
    if (s.frame) e.frame = s.frame;
    if (s.blend) e.blend = true;
    return e;
  });
}
writeFileSync(path.join(FILMS, 'kavach-short.edit.json'), JSON.stringify({
  note: 'Generated by films/short/edit.mjs from kavach-short.plan.json. Edit that, not this.', map,
}, null, 1) + '\n');
const stretched = Object.entries(map).flatMap(([beat, parts]) => parts
  .filter((p) => p.to != null).map((p) => ({ beat, ref: p.ref, x: p.seconds / (p.to - p.from) })).filter((p) => p.x > 1.32 || p.x < 0.7));
console.log(`  ${Object.keys(map).length} beats → films/kavach-short.edit.json`);
for (const s of stretched) console.log(`  ! ${s.beat} ${s.ref} plays at ${(1 / s.x).toFixed(2)}x`);
