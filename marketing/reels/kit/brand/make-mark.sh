#!/bin/sh
# Regenerates kit/brand/logo/mark-path.js from the app's own traced mark.
cd "$(dirname "$0")/../../../.." || exit 1
node -e "
const s=require('fs').readFileSync('mdg-client/src/components/BrandMark.tsx','utf8');
const m=s.match(/const MARK_PATH =\s*\n?\s*'([^']+)'/); if(!m) throw new Error('MARK_PATH not found');
require('fs').writeFileSync('marketing/reels/kit/brand/logo/mark-path.js', '// The real MDG mark: the traced outline from mdg-client/src/components/BrandMark.tsx\n// (even-odd fill, viewBox \"-11.5 0 1024 1024\"). GENERATED by kit/brand/make-mark.sh — do not edit.\nwindow.Kit = window.Kit || {};\nwindow.Kit.MARK_PATH = ' + JSON.stringify(m[1]) + ';\n');"
